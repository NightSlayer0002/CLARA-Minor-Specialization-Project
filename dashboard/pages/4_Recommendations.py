import sys
import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "../..")))

import streamlit as st
import pandas as pd
from dashboard.utils.data_access import (
    get_recommendations,
    update_recommendation_status,
    check_db_exists,
    get_audit_metadata
)
from dashboard.components.charts import recommendation_savings_bar
from dashboard.utils.risk_tiers import TIER_BADGES

# Configure Recommendations screen
st.set_page_config(
    page_title="Remediation Actions - CLARA", 
    layout="wide", 
    page_icon="🧠",
    initial_sidebar_state="expanded"
)

st.title("GenAI Recommendations & Remediation")
st.write(
    "Prioritized remediation action plans generated by Google Gemini (`gemini-3.8-flash`) or "
    "CLARA's deterministic rule engine (offline fallback). Review, approve, and track governance state."
)

exists, _ = check_db_exists()
if exists:
    # Query all recommendations to feed the top bar chart and audit status
    all_recs = get_recommendations()
    
    # 1. Informational disclaimer if offline fallback or legacy records are present
    if not all_recs.empty and "generation_source" in all_recs.columns:
        has_offline = (all_recs["generation_source"] == "offline_fallback").any()
        has_gemini = (all_recs["generation_source"] == "gemini").any()
        has_legacy = (all_recs["generation_source"] == "legacy_unknown").any()
        
        if has_legacy:
            st.info(
                "ℹ️ **Legacy Records Present**: Historical recommendation records exist from prior pipeline versions "
                "with unverified origins and are marked as 'Legacy source unknown'. Newly generated records carry verified provenance."
            )
        elif has_offline and not has_gemini:
            st.info(
                "ℹ️ **Deterministic Fallback Active**: Recommendations below were generated by CLARA's deterministic rule engine "
                "because the Gemini API was unconfigured or offline. Connect a `GEMINI_API_KEY` to enable live `gemini-3.8-flash` reasoning."
            )
        elif has_offline and has_gemini:
            st.info(
                "ℹ️ **Hybrid Active**: Displaying both live `gemini-3.8-flash` recommendations and deterministic offline fallbacks."
            )
        elif has_gemini:
            st.success(
                "🤖 **Live Gemini Reasoning Active**: All recommendations below were produced by `gemini-3.8-flash` "
                "with structured Pydantic schema validation and authoritative application-controlled provenance."
            )

    # 2. Savings Bar Chart at Top of page
    if not all_recs.empty:
        fig_savings = recommendation_savings_bar(all_recs)
        st.image(fig_savings.to_image(format="png", width=760, height=420, scale=2), use_column_width=True)
        st.divider()
        
    # 3. Filters layout inside the screen
    filter_col1, filter_col2 = st.columns(2)
    with filter_col1:
        priority_filter = st.selectbox(
            "Filter by Operational Priority:", 
            options=["All", "Critical", "High", "Medium", "Low"],
            index=0
        )
    with filter_col2:
        status_filter = st.selectbox(
            "Filter by Governance Status:", 
            options=["All", "Pending", "Approved", "Rejected", "Archived"],
            index=0
        )
        
    # Query filtered list
    filtered_recs = get_recommendations(priority_filter, status_filter)
    
    # 4. Render expandable recommendation cards with provenance badges
    if filtered_recs.empty:
        st.info("No recommendations found matching the selected priority and status filters.")
    else:
        st.caption(f"Displaying **{len(filtered_recs)}** actionable recommendation plan(s):")
        
        for idx, row in filtered_recs.iterrows():
            rec_id = row["recommendation_id"]
            p_badge = TIER_BADGES.get(row["priority"], "⚪")
            
            src = row.get("generation_source", "offline_fallback")
            if src == "gemini":
                src_badge = "🤖 [Gemini]"
            elif src == "legacy_unknown":
                src_badge = "🏷️ [Legacy Source Unknown]"
            else:
                src_badge = "⚙️ [Offline Fallback]"

            provider_info = f" | {row.get('cloud_provider', 'Cloud')} ({row.get('region', 'Global')})" if pd.notna(row.get('cloud_provider')) else ""
            header = f"{p_badge} [{row['priority']}] {src_badge} {row['title']} — Instance: {row['instance_id']}{provider_info}"
            
            with st.expander(header, expanded=(idx == 0)):
                # Provenance and Model Badge
                model_name = row.get("model_name", "deterministic_rule_engine")
                gen_at = row.get("generated_at", "N/A")
                reason = row.get("fallback_reason")

                if src == "gemini":
                    st.caption(f"🤖 **Live Gemini Generated** | Model: `{model_name}` | Generated At: {gen_at}")
                elif src == "legacy_unknown":
                    st.caption(f"🏷️ **Legacy Source Unknown** | Pre-migration record | Model: unknown | Generated At: {gen_at}")
                else:
                    reason_label = f" | Reason: `{reason}`" if reason else ""
                    st.caption(f"⚙️ **Deterministic Fallback Engine** | Generator: `{model_name}`{reason_label} | Generated At: {gen_at}")

                st.markdown(f"**Description & Observed Telemetry:**  \n{row['description']}")
                
                # Split implementation steps by delimiter
                st.markdown("**Actionable Remediation Steps:**")
                steps = str(row["implementation_steps"]).split(" | ")
                for step_idx, step in enumerate(steps, 1):
                    st.markdown(f"{step_idx}. {step}")
                
                # Expected Benefit (if persisted)
                benefit = row.get("expected_benefit")
                if benefit and pd.notna(benefit) and str(benefit).strip() and str(benefit).lower() != "none":
                    st.markdown(f"**Expected Benefit:**  \n*{benefit}*")
                    
                # Metadata metrics row
                m_col1, m_col2, m_col3, m_col4 = st.columns(4)
                with m_col1:
                    st.metric("Estimated Effort", f"{row['estimated_effort_hours']} hrs")
                with m_col2:
                    st.metric("Estimated Savings", f"${row['estimated_savings_usd']:.2f}/mo")
                with m_col3:
                    st.metric("Current Status", row["status"].upper())
                with m_col4:
                    st.metric("Instance Type", str(row.get("instance_type", "N/A")))
                    
                # Action approval buttons row
                st.markdown("**Governance Actions:** *(Approval updates internal governance tracking; does not alter live cloud resources)*")
                act_col1, act_col2, act_col3 = st.columns(3)
                with act_col1:
                    if st.button("✅ Approve Plan", key=f"app_{rec_id}", use_container_width=True):
                        update_recommendation_status(rec_id, "approved")
                        st.success(f"Plan {rec_id[:8]} marked as Approved in governance records!")
                        st.rerun()
                with act_col2:
                    if st.button("❌ Reject / Dismiss", key=f"rej_{rec_id}", use_container_width=True):
                        update_recommendation_status(rec_id, "rejected")
                        st.warning(f"Recommendation {rec_id[:8]} marked as Rejected.")
                        st.rerun()
                with act_col3:
                    if st.button("📦 Archive Plan", key=f"arc_{rec_id}", use_container_width=True):
                        update_recommendation_status(rec_id, "archived")
                        st.info(f"Recommendation {rec_id[:8]} moved to archive.")
                        st.rerun()
                        
    st.divider()
    
    # 5. Governance Status History
    st.subheader("📋 Governance Status History")
    st.caption("Chronological system execution records and recommendation activity history.")
    
    audit_data = get_audit_metadata()
    total_inst = audit_data["total_instances"]
    calc_time_str = audit_data["calc_time_str"]
    gen_time_str = audit_data["gen_time_str"]
    rec_count = audit_data["recommendation_count"]
    sources = audit_data.get("generation_sources", [])

    if "gemini" in sources and "offline_fallback" in sources:
        remediation_line = f"[{gen_time_str}] GENAI/FALLBACK: Processed high-risk instances with Gemini API (gemini-3.8-flash) & deterministic fallback."
    elif "gemini" in sources:
        remediation_line = f"[{gen_time_str}] GENAI: Sent high-risk instances to Gemini API (gemini-3.8-flash) for remediation guidance."
    elif "legacy_unknown" in sources:
        remediation_line = f"[{gen_time_str}] SYSTEM: Ingested pre-migration recommendation records (legacy source unknown)."
    else:
        remediation_line = f"[{gen_time_str}] REMEDIATION: Generated deterministic fallback recommendations via rule engine (offline mode)."

    st.code(f"""
[{calc_time_str}] SYSTEM: Ingested telemetry for {total_inst} instances ({audit_data.get('total_metrics_records', 27000):,} records).
[{calc_time_str}] ANALYTICS: Multi-Modal Isolation Forest and Security scoring completed.
{remediation_line}
[{gen_time_str}] GOVERNANCE: Ingested {rec_count} recommendations with status 'Pending'.
    """.strip(), language="text")
